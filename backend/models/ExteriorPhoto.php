<?php

namespace backend\models;

use backend\models\serves\ExteriorUserRecordServes;
use Yii;
use yii\db\Exception;

/**
 * This is the model class for table "nxp_exterior_photo".
 * @property int         $id
 * @property int|null    $exterior_user 外部用户
 * @property int|null    $record_id     入场登记id
 * @property string|null $file_id       文件
 * @property int|null    $create_user   创建人
 * @property int|null    $create_time   创建时间
 * @property int|null    $update_time   更新时间
 * @property int|null    $delete_time   删除时间
 */
class ExteriorPhoto extends \backend\models\Base
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'nxp_exterior_photo';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [ [ 'exterior_user', 'record_id', 'create_user', 'create_time', 'update_time', 'delete_time' ], 'integer' ],
            [ [ 'file_id' ], 'string', 'max' => 30 ],
        ];
    }

    public function behaviors()
    {
        return [ $this->getTimestampBehaviorArray() ]; // TODO: Change the autogenerated stub
    }

    /**
     * 保存文件信息
     * @param $record_id
     * @param $file_id
     * @return bool
     */
    public function saveFile($record_id, $file_id)
    {
        $model = self::findOne([ 'record_id' => $record_id ]);
        if (empty($model)) {
            $model = new self;
            $model->setAttributes([
                'exterior_user' => $this->getExterUserId($record_id)->exterior_user,
                'record_id'     => $record_id,
                'create_user'   => Yii::$app->user->id,
                'file_id'       => $file_id
            ]);
        } else {
            $model->file_id = $file_id;
        }
        if ($model->save()) {
            return true;
        } else {
            $this->addErrors($model->getErrors());
            return false;
        }
    }

    /**
     * 查询照片
     * @return array|FileInfo[]
     */
    public function setFilePath()
    {
        $files = [];
        if (!empty($this->file_id)) {
            $ids   = json_decode($this->file_id, 1);
            $files = ( new FileInfo() )->getPathByIds($ids);
        }
        return $files;
    }

    /**
     * 根据id查询图片
     * @param $id
     * @return array|\yii\db\ActiveRecord|null
     */
    public function getImageById($id)
    {
        return self::find()->alias('ep')
            ->select('f.*')
            ->innerJoin([ 'f' => FileInfo::tableName() ], 'ep.file_id = f.id')
            ->asArray()
            ->where([ 'ep.record_id' => $id ])
            ->one();
    }

    /**
     * 根据记录查询是否上传照片
     * @param $record_id
     * @return bool
     */
    public function ifThereIsImgByRecordId($record_id)
    {
        return self::find()->where([ 'record_id' => $record_id ])->exists();

    }

    /**
     * 查询入场的外部用户的id
     * @param $record_id
     * @return array|\yii\db\ActiveRecord|null
     */
    public function getExterUserId($record_id)
    {
        return ( new ExteriorUserRecord() )->getRecordUserId($record_id);
    }

    /**
     * 保存照片
     * @param ExteriorUserRecordServes $model
     * @return bool
     * @throws Exception
     */
    public function savePhoto(ExteriorUserRecordServes $model)
    {
        $session = Yii::$app->session;
        $files   = $session->get('photo' . $model->exteriorUser->phone);
        if (empty($files)) {
            $this->addError('id', '请拍照！');
            return false;
        }
        $this->setAttributes([
            'exterior_user' => $model->exterior_user,
            'record_id'     => $model->id,
            'file_id'       => json_encode($files)
        ]);
        if ($this->save()) {
            $session->remove('photo' . $model->exteriorUser->phone);
            return true;
        }
        return false;
    }

    /**
     * 保存照片
     * @param ExteriorUserRecordServes $model
     * @return bool
     * @throws Exception
     */
    public function saveCamera(ExteriorUserRecordServes $model, $files = [])
    {
        $this->setAttributes([
            'exterior_user' => $model->exterior_user,
            'record_id'     => $model->id,
            'file_id'       => json_encode($files)
        ]);
        if ($this->save()) {
            return true;
        }
        return false;
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id'            => 'ID',
            'exterior_user' => 'Exterior User',
            'record_id'     => 'Sorter ID',
            'file_id'       => 'File ID',
            'create_user'   => 'Create User',
            'create_time'   => 'Create Time',
            'update_time'   => 'Update Time',
            'delete_time'   => 'Delete Time',
        ];
    }
}
