<?php
namespace backend\widgets;

use yii\helpers\ArrayHelper;
use yii\web\JsExpression;
use kartik\select2\Select2;
use backend\models\UserInfo;

class SearchUser extends Select2{

    public $url;
    public $localSearch = false;

    public $dataKey = 'search-data-key';
    public $pastDate = 5;
    public function run()
    {
        $this->setOptions();
        $this->setPluginOptions();
        $this->initValue();
        parent::run(); // TODO: Change the autogenerated stub
    }


    public function setPluginOptions(){

        $pluginOptions = [
            'id' =>  new JsExpression("function(rs) { return rs.taskId; }"),
            'placeholder' => '请输入或选择用户',
            'allowClear' => false,
            'language' => [
                'errorLoading' => new JsExpression("function () { return 'Waiting...'; }"),
            ],
            'escapeMarkup' => new JsExpression('function (markup) { return markup; }'),
            'templateResult' => new JsExpression('function(res) { return res.text; }'),
            'templateSelection' => new JsExpression('function (res) { return res.text; }'),

        ];

        $this->pluginOptions = array_merge($pluginOptions,$this->pluginOptions);
        if($this->localSearch){
            $this->getDefaultData();
        }else{
            $this->pluginOptions['ajax'] = [
                'url' => $this->url,
                'dataType' => 'json',
                'data' => new JsExpression('function(params) { return {keyword:params.term}; }')
            ];
        }
    }

    public function setOptions(){
        $options = [
            'multiple' => false,
            'lay-ignore' => true,
        ];
        $this->options = array_merge($options,$this->options);
    }

    public function initValue(){

        //单选
        if($this->options['multiple'] == false && !empty($this->value)){
            if(empty($this->initValueText)){
                $this->initValueText = (new UserInfo)->getUserName($this->value);
            }
        //多选
        }else{

            if(!empty($this->value) && !is_array($this->value)){
                $id = explode(',',$this->value);
                $this->value = explode(',',$this->value);
            }elseif (is_array($this->value)){
                $id = $this->value;
            }

            if(!empty($id) && is_array($id) && empty($this->initValueText)){
                $this->initValueText = (new UserInfo)->getNameById($id);
            }
        }
    }

    public function getDefaultData(){

        $cache = \Yii::$app->cache;
        $cacheData = $cache->get($this->dataKey);
        if(!empty($cacheData) && $cacheData['past-date'] < time()){
            $this->data = $cacheData['data'];
        }else{
            $query = UserInfo::find()->asArray()->select('id,name as text')->andWhere(['>','role_id',1]);
            $this->data = ArrayHelper::map($query->all(),'id','text');
            $cache->set($this->dataKey,[
                'data' => $this->data,
                'past-date' => time()+ $this->pastDate * 60 * 60
            ]);
        }

    }

}