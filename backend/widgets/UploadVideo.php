<?php
namespace backend\widgets;

use yii\base\Widget;
use yii\helpers\Html;

class UploadVideo extends Widget{

    public $value;

    public function run()
    {
        $this->registerView();
        parent::run(); // TODO: Change the autogenerated stub
    }

    public function registerView(){
        $html = '<label for="tel" class="layui-form-label">
                    <span class="x-red">*</span>
                    <label class="control-label" for="trainvideo-name">视频</label>:
                </label>
                <div class="layui-upload upload-div" style="margin-left: 110px;">
                    <button type="button" class="layui-btn upload-file">请选择文件</button>
                    <div class="layui-upload-list">
                        <table class="layui-table" style="width: 800px;">
                            <thead>
                            <tr>
                                <th>文件名</th>
                                <th>文件大小</th>
                                <th>进度</th>
                                <th>操作</th>
                            </tr>
                            </thead>
                            <tbody id="demoList">';
        if(!empty($this->value)){
            foreach ($this->value as $key => $value){
                $html .= '<tr>
                            <td>'.substr($value,strrpos($value,'/') +1).'</td>
                            <td>'.\common\models\Upload::getFileSize($value).'</td>
                            <td></td>
                            <td>
                                <a href="javascript:;" class="layui-btn layui-btn-xs layui-btn-danger delete-video">删除</a>
                                <input type="hidden" name="upload_file[]" value="'.$value.'">
                            </td>
                        </tr>';
            }
        }
        $html .= '        </tbody>
                        </table>
                    </div>
                    <input id="video_file" type="file" class="layui-input" style="visibility: hidden">
                </div>';
        echo $html;
        $this->registerCss();
        $this->registerJs();
    }

    public function registerCss(){
        $this->view->registerCss('    
                #progress{
                width: 300px;
                height: 20px;
                background-color:#f7f7f7;
                box-shadow:inset 0 1px 2px rgba(0,0,0,0.1);
                border-radius:4px;
                background-image:linear-gradient(to bottom,#f5f5f5,#f9f9f9);
            } 
            .finish{
                background-color: #149bdf;
                background-image:linear-gradient(45deg,rgba(255,255,255,0.15) 25%,transparent 25%,transparent 50%,rgba(255,255,255,0.15) 50%,rgba(255,255,255,0.15) 75%,transparent 75%,transparent);
                background-size:40px 40px;
                height: 100%;
            }
//            form{
//                margin-top: 50px;
//            }'
        );
    }

    public function registerJs(){
        $this->view->registerJsFile('@web/js/upload-video.js');
    }

}