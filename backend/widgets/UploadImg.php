<?php
namespace backend\widgets;

use backend\models\FileInfo;
use phpDocumentor\Reflection\DocBlock\Tag;
use yii\base\Widget;
use yii\helpers\Html;
use yii\helpers\Json;
use yii\web\View;

class UploadImg extends Widget{

    public $url;
    public $name;
    public $value;
    public $disabled = false;
    public $label ='文件';
    public $required = false;
    protected $defaultImg = '/images/file.jpg';

    public function run()
    {
        if(empty($this->url)){
            $this->url = '/upload/upload';
        }
        if(empty($this->name)){
            $this->name = 'upload_file';
        }

        $this->renderView();
        $this->renderjs();
        parent::run(); // TODO: Change the autogenerated stub
    }

    public function renderView(){

    $th = "<tr>
            <th>文件</th>
            <th>文件名</th>
            <th>状态</th>
            <th>操作</th>
          </tr>";
    $thead = Html::tag('thead',$th);


    $imgTr = $this->setImagePath();

    $tbody = Html::tag('tbody',$imgTr,['id' => 'imgTbody']);

    $table = Html::tag('table',$thead.$tbody,['class' => 'layui-table']);
    $div = Html::tag('div',$table,['class' => 'layui-upload-list','style' => 'width: 800px;']);
    if($this->disabled){
        $upBut = '';
        $subBut = '';
    }else{
        $upBut = Html::button('请选择文件',['class' => 'layui-btn layui-bg-cyan','id' => 'imgList']);
        $subBut = Html::button('开始上传',['class' => 'layui-btn','id' => 'imgAction']);
    }
    $label = Html::tag('label',$this->getLabelText(),['for' => 'tel','class' => 'layui-form-label']);
    echo $label.Html::tag('div',$upBut.$div.$subBut,['class' => 'layui-upload' ,'style' => 'margin-left: 110px;']);
    }

    public function getLabelText(){
        if($this->required){
            return Html::tag('span','*',['class' => 'x-red']).$this->label.':';
        }else{
            return $this->label.':';
        }
    }


    public function setImagePath(){
        $tr = '';
        if(empty($this->value)){
            return $tr;
        }

        if(is_string($this->value)){
            $this->value = explode(',',$this->value);
        }
        $fileModel = (new FileInfo)->getFileInfoById($this->value);

        if(!empty($fileModel)){
            $deleteBtn = Html::button('删除',['class' => 'layui-btn layui-btn-xs layui-btn-danger delete-file']);

            foreach ($fileModel as $value){
                $path = (new FileInfo())->getPathUrl($value['path']);

                $hidden = Html::input('hidden',$this->name.'[]',$value['id'] );
                $tr .= '<tr>'.
                    Html::tag('td',Html::tag('a','<img src="'.$path.'"/>' )).
                    Html::tag('td',$value['name']).

                    Html::tag('td',Html::tag('span','上传成功',['style' => 'color: #5FB878']).$hidden);
                if(!$this->disabled){
                    $tr .= Html::tag('td',$deleteBtn);
                }
                $tr .=  '</tr>';
            }
        }

        return $tr;
    }


    public function renderJs(){
        $js = <<<JS
            $('#imgAction').click(function () {
                var content = $("#imgTbody").html();
                if (content== null || content == 0) {
                    layer.msg("请选择文件")
                }
            });
            layui.use('upload', function(){
                var $ = layui.jquery,upload = layui.upload;
                var demoListView = $('#imgTbody')
                    ,uploadListIns = upload.render({
                    elem: '#imgList'
                    ,url: "{$this->url}" //改成您自己的上传接口
                    ,accept: 'file'
                    ,multiple: true
                    ,auto: false
                    ,bindAction: '#imgAction'
                    ,choose: function(obj){
                        var files = this.files = obj.pushFile(); //将每次选择的文件追加到文件队列
                        //读取本地文件
                        obj.preview(function(index, file, result){
                            let showPath = getShowImgPath(result);
                            console.log(showPath)
                            var tr = $(['<tr id="upload-'+ index +'">'
                                ,'<td><img src="'+ showPath +'"/></td>'
                                ,'<td>'+ file.name +'</td>'
                                ,'<td>等待上传</td>'
                                ,'<td>' 
                                ,'<button class="layui-btn layui-btn-xs layui-btn-danger demo-delete">删除</button>'
                                ,'</td>'
                                ,'</tr>'].join(''));
            
                            //单个重传
                            tr.find('.demo-reload').on('click', function(){
                                obj.upload(index, file);
                            });
            
                            //删除
                            tr.find('.demo-delete').on('click', function(){
                                delete files[index]; //删除对应的文件
                                tr.remove();
                                uploadListIns.config.elem.next()[0].value = ''; //清空 input file 值，以免删除后出现同名文件不可选
                            });
            
                            demoListView.append(tr);
                        });
                    }
                    ,done: function(res, index, upload){
                        if(res.path){ //上传成功
                            var tr = demoListView.find('tr#upload-'+ index),tds = tr.children();
                            tds.eq(2).html('<span style="color: #5FB878;">上传成功</span>');
                            tds.eq(2).append('<input type="hidden" name="{$this->name}[]" value="'+res.id+'">'); 
                            return delete this.files[index]; //删除文件队列已经上传成功的文件
                        }
                        this.error(index, upload);
                    }
                    ,error: function(index, upload){
                        var tr = demoListView.find('tr#upload-'+ index),tds = tr.children();
                        tds.eq(1).html('<span style="color: #FF5722;">上传失败</span>');
                        tds.eq(2).find('.demo-reload').removeClass('layui-hide'); //显示重传
                        //    $("#testListAction").text('上传文件').attr("disabled","disabled").removeClass("layui-disabled");
                        //    $("#testListAction").removeAttr('disabled');
                    }
                });
            });
            //显示大图
            $(document).on('click','.show-img',function(){
                var url = $(this).attr('src');
                window.open(url);
            });
            
            $(document).on('click','.delete-file',function() {
                let _this = $(this);
                layer.confirm('是否确定删除该文件？',function(index){
                    
                    _this.parents('tr').remove();
                    layer.close(index);
                }); 
            });
            
            //非图片文件显示默认图标
            function getShowImgPath(path){
                let start = path.indexOf(':'),
                end = path.indexOf('/'),
                ext = path.substring(start + 1 ,end).toUpperCase(); 
                if(ext !== 'IMAGE' ){ 
                    console.log("{$this->defaultImg}");
                    return "{$this->defaultImg}"
                }else{ 
                    return path; 
                }
            }

JS;

        return $this->view->registerJs($js);
    }

}