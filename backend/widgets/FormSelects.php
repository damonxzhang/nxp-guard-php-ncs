<?php
namespace backend\widgets;

use backend\models\Gemba;
use backend\models\UserInfo;
use backend\models\UserStation;
use yii\helpers\Url;
use yii\base\Widget;
use yii\db\Exception;
use yii\helpers\ArrayHelper;

class FormSelects extends Widget{

    public $selectText;//label名称
    public $selectId;//节点id
    public $value;//默认数据
    public $section;//区域
    public $selectName;//表单name
    public $connectUser; //基础的用户数据
    public $url;
    public $required = false;//是否必填
    public $selectList = [];//筛选条件下拉框
    public $addSelectList = [];//附加选择框 在不改变原有的基础上增加新的筛选
    public $selectKeys ;
    public $options;

    private $valueArray;//转换后的默认值

    public function init()
    {
        if(empty($this->selectId)){
            throw new Exception('缺少参数selectId');
        }
        if(empty($this->selectId)){
            throw new Exception('请输入搜索id');
        }
        if(!empty($this->value) && !is_string($this->value)){
            throw new Exception('默认选中值必须是字符串');
        }

        if(empty($this->connectUser)){
            throw new Exception('默认用户数据不能为空');
        }

        if(empty($this->options['style'])){
            $this->options['style'] = 'width:800px;';
        }

        if(empty($this->options['class'])){
            $this->options['class'] = 'layui-input-inline';
        }

        $this->required && $this->required = 'required';
        if(!empty($this->value)){
            $this->valueArray = explode(',',$this->value);
        }
        if(empty($this->selectName)){
            $this->selectName = 'name';
        }

        if(empty($this->url)){
            $this->url = Url::to(['user-info/search-user']);
        }

        if(empty($this->selectText)){
            $this->selectText = '用户';
        }
        //设置可筛选条件
        $this->setSelectList();
        //设置筛选条件id
        $this->getSelectId();

    }

    public function run()
    {

        $this->showViewHtml();
        $this->setJs();
        parent::run(); // TODO: Change the autogenerated stub
    }

    /**
     *  设置筛选条件
     */
    public function setSelectList(){
        if(empty($this->selectList)){
            if(!empty($this->section)){
                $this->selectList['section'] = [ 'data' =>[$this->section['id'] => $this->section['value']] ];
            }

            $this->selectList = $this->selectList + [
                'position' => [
                    'text' =>'请选择职务',
                    'data'=> UserInfo::$positionArr,
                ],
                'shift' => [
                    'text' =>'请选择班别',
                    'data'=> UserInfo::$shiftArr,
                ],

                'user-stations' => [
                    'text' =>'请选择站别',
                    'data'=> ArrayHelper::map((new UserStation())->getStation(),'id','station'),
                ],
            ];
        }
        if(!empty($this->addSelectList)){
            $this->selectList = array_merge($this->selectList,$this->addSelectList);
        }

    }

    /**
     * 设置筛选条件id
     * @return bool
     */
    public function getSelectId(){
        if(empty($this->selectList)){
            return false;
        }
        $selectKeys = [];
        foreach (array_keys($this->selectList) as $val){
            $selectKeys[$val] = $this->selectId."-".$val;
        }
        $selectKeys['section'] = $this->selectId."-".'section';
        $this->selectKeys = json_encode($selectKeys);
    }
    //小部件js
    public function setJs(){
        $js =<<<JS
            var formSelects = layui.formSelects;
            //页面加载完成 重新初始化插件 避免样式错位
            $(function() {
                
                formSelects.render("$this->selectId");    
            });
            $(function(){
                
                function getData(params,_this){
                     var selectId = _this.parents('.parent-div').attr('data-key'); 
                     var selectData =  formSelects.value(selectId,'all');
                     $.post({
                        url:"$this->url",
                        data:params,
                        dataType:'json',
                        success:function(result){
                            if(result.status == 200){ 
                                
                                var content = '<option value="">直接选择或搜索选择</option>';
                    
                                $.each(result.data, function (i, val) {
                                    content += '<option value="' + val.id + '">' + val.name + '</option>';
                                });
                    
                                if(selectData){
                    
                                    var selectVal = Array();
                                    $.each(selectData, function (i, val) {
                                        selectVal.push(val.value);
                                        content += '<option value="' + val.value + '">' + val.name + '</option>';
                                    });
                                } 
                                var s = $("#"+selectId);
                                s.html(content);
                    
                                formSelects.render(selectId);
                                formSelects.value(selectId,selectVal);
                                layer.msg('操作成功！')
    
                            }else{
    
                                layer.msg(result.msg)
                            }
                        }
                    })
                }
                
                //重置搜索
                $('.$this->selectId-reload-key').click(function(){
                    var select = "dd[lay-value='']"; 
                    var arr = $this->selectKeys; 
                    var params = {$this->selectKeys};
                    $.each(arr,function(i,v){ 
                        arr[i] = $('#'+v).find('dl').find(select).click();
                        params[i] = $('#'+v).find('dl').find('.layui-this').attr('lay-value');
                    }); 
                    
                    getData(params,$(this));
                }); 
                //搜索
                $('.$this->selectId-search-user').click(function () { 
                   
                    var arr = {$this->selectKeys};
                    
                    $.each(arr,function(i,v){ 
                        arr[i] = $('#'+v).find('dl').find('.layui-this').attr('lay-value');
                    }); 
                    getData(arr,$(this));
                   
    
                });
            }) 
JS;

        $this->view->registerJs($js);

    }

    //小部件html部分
    public function showViewHtml(){

        $html = '<div class="layui-form-item parent-div" data-key="'.$this->selectId.'">
                    <label for="pwd" class="layui-form-label">
                        <span class="x-red">*</span> '.$this->selectText.'筛选:
                    </label> ';
        if(!empty($this->selectList)){
            foreach ($this->selectList as $key => $value){
                $html .= "<div class='layui-col-md1' id='".$this->selectId."-".$key."'>
                <select class='layui-col-md1' >";
                if(!empty($value['text'])){
                    $html .=  "<option value=''>".$value['text']."</option>";
                }

                foreach ($value['data'] as $k => $v){
                    $html .= "<option value='".$k."'>".$v."</option>";
                }

                $html .= " </select></div>";
            }
        }

        $html .= "  <input type='button' value='重置条件' style='margin-left: 10px;' class='layui-col-md1 layui-btn layui-btn-primary  ".$this->selectId."-reload-key'  >

        <input type='button' value='搜索'   class='layui-col-md1 layui-btn layui-btn-primary ".$this->selectId."-search-user' >

        </div>
    
        <div class='layui-form-item'>
            <label for='pwd' class='layui-form-label'>
                <span class='x-red'>*</span> ".$this->selectText.":
            </label>
            <div class='".$this->options['class']."' style='".$this->options['style']."'>
                <select name='".$this->selectName."' id='$this->selectId' lay-verify='".$this->required."' xm-select='$this->selectId'"."= xm-select-search=''>
                    <option value=''>直接选择或搜索选择</option>";
                    foreach ($this->connectUser as $value):
                        $html .=  "<option value='".$value['id']."'";
                        if(!empty($this->valueArray) && in_array($value['id'],$this->valueArray)){
                            $html .= "selected";
                        }
                        $html.=" >".$value['name'] ."</option>";
                    endforeach;
        $html .="</select>
            </div>
        </div>";
        echo $html;

    }

}