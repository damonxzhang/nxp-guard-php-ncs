<?php
namespace common\models;

use yii\base\Behavior;
use yii\web\UploadedFile;
use Yii;

class Upload extends Behavior {

    const VEDIO_TYPE = 'video';
    const IMAGE_TYPE = 'image';

    public function init()
    {
        $this->default_path = Yii::$app->params['file_path'];
        $this->setPath();
        parent::init(); // TODO: Change the autogenerated stub
    }

    public $file_types = [
        self::VEDIO_TYPE => '视频',
        self::IMAGE_TYPE => '图片'
    ];
    public $type;
    private $default_path;
    private $path;
    private $folder;


    public function setType($type){
        $this->type = $type;
    }
    public function getType(){
        return $this->type;
    }

    /**
     * 保存文件
     * @return array
     */
    public function save(){

        $file = UploadedFile::getInstanceByName('file');
        if(!empty($this->type) && $this->type !== substr($file->type,0,strpos($file->type,'/'))){
            return ['code' => 100, 'message' => '请根据要求上传文件！'];
        }

        if (!$file) {
            return ['code' => 100, 'message' => '文件上传失败，请稍后再尝试!'];
        }

        $fileName =  $file->baseName . time() . '.' . $file->extension;
        $filePath = $this->path . $fileName;
        if (file_exists($filePath)) {
            return ['code' => 100, 'message' => '此文件已经存在啦!'];
        }

        if (!is_dir( $this->path)) {
            mkdir( $this->path, 0777,true);//递归方式创建数组
        }

        $uploadResult = $file->saveAs($filePath);

        if ($uploadResult) {
            $size = round($file->size/100000,2).'mb' ;
            return ['code' => 200, 'message' => '上传成功!', 'path' => Yii::$app->params['video_url'].$this->folder.$fileName,'size'=>$size];
        }else{

            return ['code' => 100, 'message' => '文件上传失败，请稍后再尝试!'];
        }
    }

    /**
     * 根据类型选择存放位置
     */
    protected function setPath(){
        $date = date('Ymd').'/';
        if(!empty($this->file_types[$this->type])){

            $path = $this->type.'/'.$date;
        } else{

            $path = 'file/'.$date;
        }
        $this->folder = $path;

        $this->path = $this->default_path.$this->folder;
    }

    public static function getFileSize($fileUrl){
        $file = @get_headers($fileUrl,1);
        if(empty($file) || empty($file['Content-Length'])){
            return  false;
        }
        $fileSize = $file['Content-Length'];
        $kb = round($fileSize/1024,1);
        if($kb < 1024){
            return $kb.'KB';
        }
        $mb = round($kb/1024,1);
        if($mb < 1024){
            return $mb.'MB';
        }
        $gb = round($mb/1024,1);
        if($mb < 1024){
            return $gb.'GB';
        }
    }
}